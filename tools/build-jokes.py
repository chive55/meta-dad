#!/usr/bin/env python3
"""Generate assets/js/jokes-data.js from the dad-jokes markdown sources.

Source of truth: ~/workspace/your_files/dad-jokes/jokes.md and
~/workspace/your_files/dad-jokes/halloween-jokes.md.
Re-run after any joke edit: python3 tools/build-jokes.py
"""
import json, re, os

BASE = os.path.expanduser("~/workspace")
SRC = os.path.join(BASE, "your_files/dad-jokes")
OUT_DIR = os.path.join(BASE, "meta-dad-website/assets/js")
OUT = os.path.join(OUT_DIR, "jokes-data.js")

def parse(path):
    jokes, cat = [], None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            m = re.match(r"^##\s+(.+)$", line)
            if m:
                cat = m.group(1)
                continue
            m = re.match(r"^\*\*(\d+)\.\*\*\s+(.+)$", line)
            if m:
                jokes.append({"n": int(m.group(1)), "category": cat, "text": m.group(2)})
    return jokes

daily = parse(os.path.join(SRC, "jokes.md"))
halloween = parse(os.path.join(SRC, "halloween-jokes.md"))
assert len(daily) == 100, f"expected 100 daily jokes, got {len(daily)}"
assert len(halloween) == 100, f"expected 100 halloween jokes, got {len(halloween)}"

os.makedirs(OUT_DIR, exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build-jokes.py from the dad-jokes markdown sources. Do not hand-edit. */\n")
    f.write("const DAD_JOKES = ")
    json.dump(daily, f, ensure_ascii=False)
    f.write(";\nconst HALLOWEEN_JOKES = ")
    json.dump(halloween, f, ensure_ascii=False)
    f.write(";\n")
print(f"wrote {OUT}: {len(daily)} daily + {len(halloween)} halloween jokes")
